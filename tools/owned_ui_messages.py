"""Inventory of owned diagnostics/history labels for presentation translation.

The core keeps English messages and locale-independent machine data. Only the
GUI presentation adapter uses these sources. Never apply it to authored names,
paths, note bodies or serialized/API enum values.
"""
from pathlib import Path
import json
import re

LITERAL=r'"(?:\\.|[^"\\])*"(?:\s*"(?:\\.|[^"\\])*")*'
def cpp_strings(source):
    source=re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/',
                  lambda m:m[0] if m[0].startswith('"') else '\n'*m[0].count('\n'),source,flags=re.S)
    for match in re.finditer(LITERAL,source):
        try:
            value=''.join(json.loads(part[0]) for part in re.finditer(r'"(?:\\.|[^"\\])*"',match[0]))
        except ValueError:continue # Raw shader/XML/JSON literals are not UI messages.
        yield value

def owned_messages(root):
    messages=set()
    for folder in ['core','io','physics']:
        for path in (root/'Editor/src'/folder).rglob('*'):
            if path.suffix not in {'.cpp','.h'}:continue
            for value in cpp_strings(path.read_text(encoding='utf-8')):
                if ('FBXHeaderExtension' not in value and not value.lstrip().startswith(('<','CREATE ','SELECT ','INSERT ','UPDATE ','DELETE '))
                    and re.search(r'[A-Za-z]+ [A-Za-z]',value) and 0<len(value)<900):messages.add(value)
    # Includes dynamically assembled diagnostics and command labels, which stay
    # in the undo/API model in their original language. This inventories source
    # literals, never the contents of live/user-authored widgets.
    for path in [*(root/'Editor/src/ui').rglob('*.cpp'),root/'Editor/src/automation/automation_ui.cpp']:
        for value in cpp_strings(path.read_text(encoding='utf-8')):
            if re.search(r'[A-Za-z]+ [A-Za-z]',value) and len(value)<900 and not value.lstrip().startswith(('#','QTool','QGroup','QDock','QTab')):
                messages.add(value)
    return messages

def write_patterns(root):
    messages=owned_messages(root)
    # Only format strings need reverse matching. Exact messages use QTranslator.
    formats=sorted(value for value in messages if re.search(r'%L?[1-9]',value))
    content='#pragma once\n// Generated by tools/update_translations.py. Do not edit.\nnamespace trickster {\ninline constexpr const char *ownedMessagePatterns[]={\n'
    content+=''.join('    '+json.dumps(value,ensure_ascii=False)+',\n' for value in formats)
    content+='};\n}\n'
    prefixes=sorted((value for value in messages if (value.endswith(': ') or value=='Opened ') and '%' not in value),key=lambda x:(-len(x),x))
    content=content[:-2]+'inline constexpr const char *ownedMessagePrefixes[]={\n'+''.join('    '+json.dumps(value,ensure_ascii=False)+',\n' for value in prefixes)+'};\n}\n'
    path=root/'Editor/src/settings/owned_message_sources.h'
    if not path.exists() or path.read_text(encoding='utf-8')!=content:path.write_bytes(content.encode('utf-8'))
    return messages
